CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  position VARCHAR(20) NOT NULL CHECK (position IN ('lead', 'senior', 'staff')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_users_position ON users(position);

CREATE TABLE departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(20) NOT NULL CHECK (name IN ('backend', 'frontend', 'unity', 'sqa', 'ld')),
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_departments_name ON departments(name);

-- Table name intentionally follows the requested schema spelling: "desicion".
CREATE TABLE desicion (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cve VARCHAR(80) NOT NULL,
  title VARCHAR(240) NOT NULL,
  context TEXT NOT NULL,
  decision TEXT NOT NULL,
  consequences TEXT NOT NULL,
  alternatives TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pengajuan' CHECK (status IN ('pengajuan', 'research', 'completed')),
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  status_updated_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_desicion_cve ON desicion(cve);
CREATE INDEX idx_desicion_status ON desicion(status);
CREATE INDEX idx_desicion_user_id ON desicion(user_id);

-- PostgreSQL uses TEXT for long text; desicion_id is UNIQUE to enforce 1:1.
CREATE TABLE history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description TEXT NOT NULL,
  desicion_id INTEGER NOT NULL UNIQUE REFERENCES desicion(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
